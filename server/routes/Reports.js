import express from "express";
import { pool } from "../db/connection.js";

const router = express.Router();


// ============================================================
// GET REPORTS
// GET /api/reports
// ============================================================

router.get("/", async (req, res) => {

    try {

        const result = await pool.query(`
            SELECT

                ir.report_id,
                ir.report_name,
                ir.report_type,
                ir.start_date,
                ir.end_date,
                ir.generated_at,
                ir.export_format,
                ir.file_path,

                CONCAT(
                    u.first_name,
                    ' ',
                    u.last_name
                ) AS generated_by_name

            FROM public.inventoryreports ir

            LEFT JOIN public.users u
                ON ir.generated_by = u.user_id

            ORDER BY ir.report_id DESC
        `);


        res.status(200).json(result.rows);

    } catch (error) {

        console.error(
            "GET reports error:",
            error
        );

        res.status(500).json({
            success: false,
            error: "Failed to fetch reports"
        });
    }
});


// ============================================================
// CREATE REPORT RECORD
// POST /api/reports
// ============================================================

router.post("/", async (req, res) => {

    const {
        report_name,
        report_type,
        generated_by,
        start_date,
        end_date,
        export_format,
        file_path
    } = req.body;


    if (!report_name) {

        return res.status(400).json({
            success: false,
            error: "Report name is required"
        });
    }


    if (!report_type) {

        return res.status(400).json({
            success: false,
            error: "Report type is required"
        });
    }


    if (!generated_by) {

        return res.status(400).json({
            success: false,
            error: "Generated by is required"
        });
    }


    try {

        const result = await pool.query(`
            INSERT INTO public.inventoryreports
            (
                report_name,
                report_type,
                generated_by,
                start_date,
                end_date,
                export_format,
                file_path
            )
            VALUES
            ($1, $2, $3, $4, $5, $6, $7)

            RETURNING *
        `, [
            report_name.trim(),
            report_type,
            Number(generated_by),
            start_date || null,
            end_date || null,
            export_format || null,
            file_path || null
        ]);


        res.status(201).json({
            success: true,
            message: "Report created successfully",
            report: result.rows[0]
        });

    } catch (error) {

        console.error(
            "POST report error:",
            error
        );

        res.status(500).json({
            success: false,
            error: "Failed to create report"
        });
    }
});


// ============================================================
// DELETE REPORT
// DELETE /api/reports/:id
// ============================================================

router.delete("/:id", async (req, res) => {

    try {

        const result = await pool.query(`
            DELETE FROM public.inventoryreports
            WHERE report_id = $1
            RETURNING report_id
        `, [Number(req.params.id)]);


        if (!result.rows.length) {

            return res.status(404).json({
                success: false,
                error: "Report not found"
            });
        }


        res.status(200).json({
            success: true,
            message: "Report deleted successfully"
        });

    } catch (error) {

        console.error(
            "DELETE report error:",
            error
        );

        res.status(500).json({
            success: false,
            error: "Failed to delete report"
        });
    }
});


export default router;