import React, { useEffect, useState } from "react";

const Reports = () => {

    const [reports, setReports] = useState([]);
    const [loading, setLoading] = useState(true);


    const fetchReports = async () => {

        try {

            const response = await fetch(
                "http://localhost:5000/api/reports"
            );

            if (!response.ok) {
                throw new Error(
                    "Failed to fetch reports"
                );
            }

            const data = await response.json();

            setReports(data);

        } catch (error) {

            console.error(
                "Reports error:",
                error
            );

        } finally {

            setLoading(false);
        }
    };


    useEffect(() => {

        fetchReports();

    }, []);


    return (
        <div className="min-h-screen bg-slate-50 p-4 md:p-6">

            <div className="mx-auto max-w-7xl">

                <div className="mb-6">

                    <h1 className="text-2xl font-bold text-slate-800">
                        Reports
                    </h1>

                    <p className="mt-1 text-sm text-slate-500">
                        Generate and view inventory reports
                    </p>

                </div>


                {/* REPORT TYPES */}

                <div className="mb-6 grid gap-4 md:grid-cols-3">

                    <div className="rounded-xl border border-slate-200 bg-white p-6 shadow-sm">

                        <div className="mb-4 text-3xl">
                            📦
                        </div>

                        <h2 className="font-semibold text-slate-800">
                            Inventory Report
                        </h2>

                        <p className="mt-1 text-sm text-slate-500">
                            View current medicine stock levels.
                        </p>

                        <button className="mt-4 rounded-lg bg-[#00549a] px-4 py-2 text-sm font-medium text-white hover:bg-[#00427a]">
                            Generate
                        </button>

                    </div>


                    <div className="rounded-xl border border-slate-200 bg-white p-6 shadow-sm">

                        <div className="mb-4 text-3xl">
                            📊
                        </div>

                        <h2 className="font-semibold text-slate-800">
                            Transaction Report
                        </h2>

                        <p className="mt-1 text-sm text-slate-500">
                            Review inventory transactions.
                        </p>

                        <button className="mt-4 rounded-lg bg-[#00549a] px-4 py-2 text-sm font-medium text-white hover:bg-[#00427a]">
                            Generate
                        </button>

                    </div>


                    <div className="rounded-xl border border-slate-200 bg-white p-6 shadow-sm">

                        <div className="mb-4 text-3xl">
                            🛒
                        </div>

                        <h2 className="font-semibold text-slate-800">
                            Order Report
                        </h2>

                        <p className="mt-1 text-sm text-slate-500">
                            Review purchase order history.
                        </p>

                        <button className="mt-4 rounded-lg bg-[#00549a] px-4 py-2 text-sm font-medium text-white hover:bg-[#00427a]">
                            Generate
                        </button>

                    </div>

                </div>


                {/* REPORT HISTORY */}

                <div className="rounded-xl border border-slate-200 bg-white shadow-sm">

                    <div className="border-b border-slate-200 p-5">

                        <h2 className="font-semibold text-slate-800">
                            Report History
                        </h2>

                    </div>


                    <div className="overflow-x-auto">

                        <table className="w-full text-left text-sm">

                            <thead className="bg-slate-50 text-xs uppercase text-slate-500">

                                <tr>

                                    <th className="px-6 py-4">
                                        Report
                                    </th>

                                    <th className="px-6 py-4">
                                        Type
                                    </th>

                                    <th className="px-6 py-4">
                                        Generated By
                                    </th>

                                    <th className="px-6 py-4">
                                        Date
                                    </th>

                                    <th className="px-6 py-4">
                                        Format
                                    </th>

                                </tr>

                            </thead>


                            <tbody className="divide-y divide-slate-100">

                                {loading ? (

                                    <tr>

                                        <td
                                            colSpan="5"
                                            className="px-6 py-10 text-center text-slate-500"
                                        >
                                            Loading reports...
                                        </td>

                                    </tr>

                                ) : reports.length === 0 ? (

                                    <tr>

                                        <td
                                            colSpan="5"
                                            className="px-6 py-10 text-center text-slate-500"
                                        >
                                            No reports generated yet.
                                        </td>

                                    </tr>

                                ) : (

                                    reports.map(
                                        (report) => (

                                            <tr
                                                key={
                                                    report.report_id
                                                }
                                                className="hover:bg-slate-50"
                                            >

                                                <td className="px-6 py-4 font-medium text-slate-800">
                                                    {
                                                        report.report_name
                                                    }
                                                </td>

                                                <td className="px-6 py-4 text-slate-600">
                                                    {
                                                        report.report_type
                                                    }
                                                </td>

                                                <td className="px-6 py-4 text-slate-600">
                                                    {
                                                        report.generated_by_name ||
                                                        "-"
                                                    }
                                                </td>

                                                <td className="px-6 py-4 text-slate-600">
                                                    {
                                                        report.generated_at
                                                            ? new Date(
                                                                report.generated_at
                                                            ).toLocaleString()
                                                            : "-"
                                                    }
                                                </td>

                                                <td className="px-6 py-4 text-slate-600">
                                                    {
                                                        report.export_format ||
                                                        "-"
                                                    }
                                                </td>

                                            </tr>

                                        )
                                    )

                                )}

                            </tbody>

                        </table>

                    </div>

                </div>

            </div>

        </div>
    );
};

export default Reports;